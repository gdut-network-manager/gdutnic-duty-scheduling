CREATE TABLE IF NOT EXISTS settings (
  `key` VARCHAR(191) PRIMARY KEY, value LONGTEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS users (
  username VARCHAR(64) PRIMARY KEY, password VARCHAR(255) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS member_accounts (
  username VARCHAR(64) PRIMARY KEY, password VARCHAR(255) NOT NULL,
  student_id VARCHAR(64) NOT NULL DEFAULT '',
  active TINYINT NOT NULL DEFAULT 1, permissions VARCHAR(191) NOT NULL DEFAULT '',
  group_id VARCHAR(64) NOT NULL DEFAULT '', sso_id VARCHAR(64) NOT NULL DEFAULT '',
  sso_auto_link_blocked TINYINT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS login_sessions (
 id CHAR(64) PRIMARY KEY, kind VARCHAR(10) NOT NULL, username VARCHAR(64) NOT NULL,
 last_activity DOUBLE NOT NULL, expires_at DOUBLE NOT NULL, sso_identity VARCHAR(64) NOT NULL DEFAULT '', last_response DOUBLE NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS keycloak_links (
 identity_key CHAR(64) PRIMARY KEY, issuer TEXT NOT NULL, subject VARCHAR(255) NOT NULL,
 username VARCHAR(64) NOT NULL UNIQUE, account_key VARCHAR(64) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS keycloak_flows (
 id CHAR(64) PRIMARY KEY, expires_at BIGINT NOT NULL, data LONGTEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS shifts (
  id BIGINT PRIMARY KEY AUTO_INCREMENT, day CHAR(10) NOT NULL,
  start CHAR(5) NOT NULL, end CHAR(5) NOT NULL, location VARCHAR(120) NOT NULL,
  note TEXT NOT NULL, special TINYINT NOT NULL DEFAULT 0, INDEX idx_shifts_day(day,start)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS attendance (
  shift_id BIGINT NOT NULL, name VARCHAR(64) NOT NULL, checked_at VARCHAR(40),
  status_override VARCHAR(16) NOT NULL DEFAULT '', final_status VARCHAR(16) NOT NULL DEFAULT '',
  PRIMARY KEY(shift_id,name),
  FOREIGN KEY(shift_id) REFERENCES shifts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS weekly_instances (
  day CHAR(10) NOT NULL, slot INT NOT NULL, shift_id BIGINT NOT NULL UNIQUE,
  PRIMARY KEY(day,slot), FOREIGN KEY(shift_id) REFERENCES shifts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE IF NOT EXISTS field_duty (
  month CHAR(7) NOT NULL, username VARCHAR(64) NOT NULL, registered_at VARCHAR(40) NOT NULL,
  manual TINYINT NOT NULL DEFAULT 0, status TINYINT NOT NULL DEFAULT 2,
  PRIMARY KEY(month,username)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE IF NOT EXISTS swaps (
  id BIGINT PRIMARY KEY AUTO_INCREMENT, shift_a BIGINT NOT NULL, name_a VARCHAR(64) NOT NULL,
  shift_b BIGINT NOT NULL, name_b VARCHAR(64) NOT NULL, created_at VARCHAR(40) NOT NULL,
  UNIQUE KEY uniq_shift_a_name (shift_a,name_a), UNIQUE KEY uniq_shift_b_name (shift_b,name_b)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE IF NOT EXISTS attendance_history (
  id BIGINT PRIMARY KEY AUTO_INCREMENT, day CHAR(10) NOT NULL, start CHAR(5) NOT NULL,
  end CHAR(5) NOT NULL, name VARCHAR(64) NOT NULL, checked_at VARCHAR(40) NOT NULL,
  location VARCHAR(120) NOT NULL DEFAULT '', note TEXT NOT NULL, archived_at VARCHAR(40) NOT NULL,
  final_status VARCHAR(16) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE IF NOT EXISTS operation_log (
  id BIGINT PRIMARY KEY AUTO_INCREMENT, at VARCHAR(40) NOT NULL,
  actor VARCHAR(64) NOT NULL, role VARCHAR(16) NOT NULL DEFAULT '',
  action VARCHAR(64) NOT NULL, detail TEXT NOT NULL,
  INDEX idx_operation_log_at (at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE IF NOT EXISTS permission_groups (
  id VARCHAR(64) PRIMARY KEY, name VARCHAR(64) NOT NULL UNIQUE,
  permissions VARCHAR(191) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE IF NOT EXISTS push_deliveries (
  id VARCHAR(64) PRIMARY KEY, period_end CHAR(10) NOT NULL, recipient VARCHAR(254) NOT NULL,
  state VARCHAR(16) NOT NULL, updated_at VARCHAR(40) NOT NULL, error TEXT NOT NULL,
  INDEX idx_push_updated(updated_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
